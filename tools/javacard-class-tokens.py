#!/usr/bin/env python3
"""Generate JC305 to embedded Java Card class-token maps from JCA exports."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys


CLASS_RE = re.compile(
    r"^\s*\.class\s+(?:(?:public|protected|private|abstract|final|static)\s+)*"
    r"([A-Za-z_$][A-Za-z0-9_$]*)\s+(\d+)\b",
    re.MULTILINE,
)
INTERFACE_RE = re.compile(
    r"^\s*\.interface\s+(?:(?:public|protected|private|abstract|final|static)\s+)*"
    r"([A-Za-z_$][A-Za-z0-9_$]*)\s+(\d+)\b",
    re.MULTILINE,
)

PACKAGES = {
    "java_lang": "java/lang/javacard/lang.jca",
    "javacard_framework": "javacard/framework/javacard/framework.jca",
    "javacard_security": "javacard/security/javacard/security.jca",
    "javacardx_crypto": "javacardx/crypto/javacard/crypto.jca",
}

SECURITY_KEY_INTERFACES = (
    "SecretKey",
    "PrivateKey",
    "PublicKey",
    "AESKey",
    "DESKey",
    "HMACKey",
    "RSAPublicKey",
    "RSAPrivateKey",
    "RSAPrivateCrtKey",
    "ECPublicKey",
    "ECPrivateKey",
)


def read_classes(path: Path) -> dict[str, int]:
    try:
        content = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ValueError(f"cannot read class export {path}: {error}") from error
    result: dict[str, int] = {}
    for name, token_text in CLASS_RE.findall(content):
        token = int(token_text)
        if token > 255:
            raise ValueError(f"{path}: class token for {name} exceeds one byte")
        if name in result:
            raise ValueError(f"{path}: duplicate class declaration {name}")
        result[name] = token
    if not result:
        raise ValueError(f"{path}: no class declarations found")
    return result


def read_interfaces(path: Path) -> dict[str, int]:
    try:
        content = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ValueError(f"cannot read interface export {path}: {error}") from error
    result: dict[str, int] = {}
    for name, token_text in INTERFACE_RE.findall(content):
        token = int(token_text)
        if token > 255:
            raise ValueError(f"{path}: interface token for {name} exceeds one byte")
        if name in result:
            raise ValueError(f"{path}: duplicate interface declaration {name}")
        result[name] = token
    return result


def generate(source_root: Path, target_root: Path, output: Path) -> None:
    arrays: list[str] = [
        "/* Generated by tools/javacard-class-tokens.py; do not edit. */",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace jcvm {",
    ]
    for package, relative_path in PACKAGES.items():
        source_classes = read_classes(source_root / relative_path)
        target_classes = read_classes(target_root / relative_path)
        missing = sorted(set(source_classes) - set(target_classes))
        if missing:
            raise ValueError(
                f"{relative_path}: embedded API is missing JC305 classes: "
                + ", ".join(missing)
            )
        tokens = list(range(max(source_classes.values()) + 1))
        for name, source_token in source_classes.items():
            tokens[source_token] = target_classes[name]
        arrays.append(
            f"inline constexpr uint8_t jc305_{package}_class_tokens[] = {{"
        )
        for offset in range(0, len(tokens), 8):
            values = ", ".join(str(value) for value in tokens[offset : offset + 8])
            arrays.append(f"    {values},")
        arrays.append("};")
        arrays.append("")
        source_interfaces = read_interfaces(source_root / relative_path)
        class_tokens = set(source_classes.values())
        source_interface_tokens = set(source_interfaces.values())
        overlapping_tokens = sorted(class_tokens & source_interface_tokens)
        if overlapping_tokens:
            raise ValueError(
                f"{relative_path}: JC305 class and interface tokens overlap: "
                + ", ".join(str(token) for token in overlapping_tokens)
            )
        target_interfaces = read_interfaces(target_root / relative_path)
        missing_interfaces = sorted(set(source_interfaces) - set(target_interfaces))
        if missing_interfaces:
            raise ValueError(
                f"{relative_path}: embedded API is missing JC305 interfaces: "
                + ", ".join(missing_interfaces)
            )
        interface_mapping = (
            list(range(max(source_interfaces.values()) + 1))
            if source_interfaces
            else []
        )
        for name, source_token in source_interfaces.items():
            interface_mapping[source_token] = target_interfaces[name]
        arrays.append(
            f"inline constexpr uint8_t jc305_{package}_interface_tokens[] = {{"
        )
        for offset in range(0, len(interface_mapping), 8):
            values = ", ".join(
                str(value) for value in interface_mapping[offset : offset + 8]
            )
            arrays.append(f"    {values},")
        arrays.append("};")
        arrays.append("")
        interface_flags = [
            1 if token in source_interface_tokens else 0
            for token in range(max(class_tokens | source_interface_tokens) + 1)
        ]
        arrays.append(
            f"inline constexpr uint8_t jc305_{package}_interface_token_flags[] = {{"
        )
        for offset in range(0, len(interface_flags), 16):
            values = ", ".join(str(value) for value in interface_flags[offset : offset + 16])
            arrays.append(f"    {values},")
        arrays.append("};")
        arrays.append("")
        if package == "javacard_security":
            for name in SECURITY_KEY_INTERFACES:
                if name not in target_interfaces:
                    raise ValueError(
                        f"{relative_path}: embedded API is missing interface {name}"
                    )
                arrays.append(
                    f"inline constexpr uint8_t rom_javacard_security_interface_{name} = "
                    f"{target_interfaces[name]};"
                )
                arrays.append(
                    f"inline constexpr uint8_t jc305_source_javacard_security_interface_{name} = "
                    f"{source_interfaces[name]};"
                )
            arrays.append("")
    arrays.extend(("} // namespace jcvm", ""))
    output.parent.mkdir(parents=True, exist_ok=True)
    generated = "\n".join(arrays)
    encoded = generated.encode("utf-8")
    if not output.is_file() or output.read_bytes() != encoded:
        output.write_bytes(encoded)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--target-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        generate(args.source_root, args.target_root, args.output)
    except ValueError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    print(f"CLASS_TOKENS:PASS output={args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
